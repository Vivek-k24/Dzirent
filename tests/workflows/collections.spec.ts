import { test, expect, type Page } from "@playwright/test";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";

type SeedProduct = { id: string; status: string; slug: string; title: string; is_available: boolean; rental_price_minor: number; featured_rank: number; created_at: string };
const manifest = JSON.parse(readFileSync(resolve(__dirname, "../../fixtures/catalog/manifest.json"), "utf8")) as { products: SeedProduct[] };
const published = manifest.products.filter(product => product.status === "published");
const cards = (page: Page) => page.locator("[data-product-id]");
const noOverflow = async (page: Page) => expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);

test("collection tree, rental filters, statewide ZIP, newest order and history work on desktop/mobile", async ({ page, isMobile }) => {
  const exceptions: string[] = [], catalogRequests: URL[] = [];
  page.on("pageerror", error => exceptions.push(error.message));
  page.on("request", request => { const url = new URL(request.url()); if (url.pathname === "/api/v1/catalog/products") catalogRequests.push(url); });
  await page.goto("/");
  await expect(cards(page)).toHaveCount(40);
  await expect(page.getByText("Prototype. Sample listings shown.", { exact: true })).toBeVisible();
  await expect(page.locator("header").getByText("Launching in Texas soon.", { exact: true })).toBeVisible();
  await expect(page.locator("#main-content .breadcrumbs")).toHaveCount(0);
  await expect(page.getByText("Only in Texas", { exact: true })).toHaveCount(0);
  await expect(page.locator("footer")).not.toContainText("Texas · Presentation prototype");
  await expect(page.getByRole("navigation", { name: "Main navigation" }).getByRole("link")).toHaveCount(2);
  await expect(page.getByRole("navigation", { name: "Main navigation" }).getByRole("link", { name: "All collections", exact: true })).toHaveAttribute("href", "/");
  await expect(page.getByRole("link", { name: "Explore Studios", exact: true })).toHaveAttribute("href", "/studios");
  await expect(page.locator(".merchandising, .mega-menu, .subcategory-pills")).toHaveCount(0);
  await expect(page.getByLabel("Sort outfits")).toHaveValue("newest");
  expect(catalogRequests[0].searchParams.get("sort")).toBe("newest");
  const newestOrder = [...published].sort((a, b) => b.created_at.localeCompare(a.created_at) || a.id.localeCompare(b.id)).map(product => product.id);
  await expect.poll(() => cards(page).evaluateAll(nodes => nodes.map(node => node.getAttribute("data-product-id")))).toEqual(newestOrder);
  await expect(page.locator("body")).toHaveCSS("background-color", "rgb(241, 241, 238)");
  await noOverflow(page);

  const mobile = isMobile || (page.viewportSize()?.width ?? 1440) < 1024;
  if (!mobile) {
    const sidebar = page.locator("#collection-sidebar");
    await expect(sidebar).toBeVisible();
    await expect(sidebar.getByRole("button", { name: "Hide categories", exact: true })).toHaveText("Categories");
    await expect(sidebar.getByRole("button", { name: "Hide categories", exact: true })).toHaveAttribute("aria-expanded", "true");
    await expect(sidebar.getByRole("checkbox")).toHaveCount(8);
    await sidebar.getByRole("button", { name: "Hide categories", exact: true }).click();
    await expect(sidebar.getByRole("button", { name: "Show categories", exact: true })).toBeFocused();
    await expect(sidebar.getByRole("button", { name: "Show categories", exact: true })).toHaveAttribute("aria-expanded", "false");
    await expect(sidebar).toBeVisible();
    await expect(sidebar.locator("#category-sidebar-content")).toBeHidden();
    await expect(page.locator(".catalog-layout")).toHaveClass(/sidebar-collapsed/);
    await sidebar.getByRole("button", { name: "Show categories", exact: true }).click();
    await expect(sidebar.getByRole("button", { name: "Hide categories", exact: true })).toBeFocused();
    await expect(sidebar.locator("#category-sidebar-content")).toBeVisible();
    await expect(page.locator(".catalog-layout")).not.toHaveClass(/sidebar-collapsed/);
  }
  const openTree = async () => {
    if (mobile) { await page.getByRole("button", { name: "Categories", exact: true }).click(); return page.getByRole("dialog", { name: "Categories", exact: true }); }
    return page.locator("#collection-sidebar");
  };
  const closeTree = async () => { if (mobile) await page.getByRole("button", { name: "View outfits", exact: true }).click(); };
  let tree = await openTree();
  await expect(tree.getByRole("checkbox")).toHaveCount(8);
  for (const children of await tree.locator(".category-children").all()) await expect(children.locator("li")).toHaveCount(5);
  await tree.getByRole("button", { name: "Expand Women subcategories", exact: true }).click();
  await expect(tree.getByRole("button", { name: "Collapse Women subcategories", exact: true })).toHaveAttribute("aria-expanded", "true");
  await tree.getByRole("checkbox", { name: "Women", exact: true }).click();
  await expect(tree.getByRole("checkbox", { name: "Women", exact: true })).toBeChecked();
  await tree.getByRole("checkbox", { name: "Men", exact: true }).click();
  await expect(cards(page)).toHaveCount(10);
  expect(new URL(page.url()).searchParams.getAll("category")).toEqual(["men", "women"]);
  await tree.getByRole("button", { name: "Dresses", exact: true }).click();
  await expect(cards(page)).toHaveCount(1);
  await expect(tree.locator('.category-children button[aria-pressed="true"]')).toHaveCount(1);
  await closeTree();
  await page.getByRole("button", { name: "Remove Dresses", exact: true }).click();
  await expect(cards(page)).toHaveCount(10);
  await page.getByRole("button", { name: "Remove Men", exact: true }).click();
  await expect(cards(page)).toHaveCount(5);
  await page.goBack(); await expect(cards(page)).toHaveCount(10);
  await page.goForward(); await expect(cards(page)).toHaveCount(5);
  await page.reload(); await expect(cards(page)).toHaveCount(5);
  tree = await openTree(); await expect(tree.getByRole("checkbox", { name: "Women", exact: true })).toBeChecked();
  if (mobile) { await page.keyboard.press("Escape"); await expect(page.getByRole("button", { name: "Categories", exact: true })).toBeFocused(); }
  await page.getByRole("button", { name: "Clear all", exact: true }).click();
  await expect(cards(page)).toHaveCount(40);

  await page.getByRole("button", { name: /^Filters/ }).click();
  let sheet = page.getByRole("dialog", { name: "Find your fit", exact: true });
  await sheet.getByRole("checkbox", { name: "Black", exact: true }).click();
  await expect(sheet.getByRole("button", { name: "Show 5 results", exact: true })).toBeEnabled();
  await page.keyboard.press("Escape"); await expect(cards(page)).toHaveCount(40);
  await page.getByRole("button", { name: /^Filters/ }).click();
  sheet = page.getByRole("dialog", { name: "Find your fit", exact: true });
  await expect(sheet.getByRole("checkbox", { name: "Black", exact: true })).not.toBeChecked();
  await sheet.getByRole("checkbox", { name: "Black", exact: true }).click();
  await sheet.getByRole("button", { name: "Show 5 results", exact: true }).click();
  await expect(cards(page)).toHaveCount(5);
  await page.getByRole("button", { name: "Remove Black", exact: true }).click(); await expect(cards(page)).toHaveCount(40);
  await page.getByLabel("Sort outfits").selectOption("featured");
  await expect(page.getByLabel("Sort outfits")).toHaveValue("featured");
  expect(new URL(page.url()).searchParams.get("sort")).toBe("featured");
  const featuredOrder = [...published].sort((a, b) => a.featured_rank - b.featured_rank || a.id.localeCompare(b.id)).map(product => product.id);
  await expect.poll(() => cards(page).evaluateAll(nodes => nodes.map(node => node.getAttribute("data-product-id")))).toEqual(featuredOrder);
  await page.getByLabel("Sort outfits").selectOption("price_asc");
  const priceOrder = [...published].sort((a, b) => a.rental_price_minor - b.rental_price_minor || a.id.localeCompare(b.id)).map(product => product.id);
  await expect.poll(() => cards(page).evaluateAll(nodes => nodes.map(node => node.getAttribute("data-product-id")))).toEqual(priceOrder);
  await page.getByRole("button", { name: "List view", exact: true }).click();
  await expect(page.locator(".product-grid")).toHaveCSS("display", "flex");
  await page.getByRole("button", { name: "Grid view", exact: true }).click();
  await expect(page.locator(".product-grid")).toHaveCSS("display", "grid");

  if (mobile) await page.getByRole("button", { name: "Open search", exact: true }).click();
  const search = mobile ? page.getByRole("dialog", { name: "Find your next look", exact: true }).getByRole("searchbox", { name: "Search outfits" }) : page.getByRole("searchbox", { name: "Search outfits" });
  await search.fill("Sherwanis"); if (mobile) await search.press("Enter");
  await expect(cards(page)).toHaveCount(1);
  await page.getByRole("button", { name: "Remove Search: Sherwanis", exact: true }).click(); await expect(cards(page)).toHaveCount(40);
  await page.getByRole("button", { name: "Delivery ZIP", exact: true }).click();
  const delivery = page.getByRole("dialog", { name: "Delivery ZIP", exact: true });
  await expect(delivery.getByRole("combobox")).toHaveCount(0);
  await delivery.getByLabel("Delivery ZIP code", { exact: false }).fill("78701");
  await expect(delivery.getByText(/Delivery estimate unavailable/)).toBeVisible();
  await delivery.getByRole("button", { name: "Save delivery ZIP", exact: true }).click();
  await expect(cards(page)).toHaveCount(40);
  await page.goto("/?metro=austin&zip=78701"); await expect(cards(page)).toHaveCount(40);
  await expect(page.getByRole("button", { name: "Delivery ZIP, 78701", exact: true })).toBeVisible();
  expect(catalogRequests.every(url => !url.searchParams.has("metro") && !url.searchParams.has("zip") && url.searchParams.has("sort"))).toBe(true);
  await noOverflow(page);
  expect(exceptions).toEqual([]);
});

test("all 40 published photo/title links resolve to their own PDP, reload, and encoded shared link", async ({ page }) => {
  test.setTimeout(135_000);
  const exceptions: string[] = [], failedAssets: string[] = [];
  page.on("pageerror", error => exceptions.push(error.message));
  page.on("response", response => { if (response.status() >= 400 && /\/(media\/|_next\/|fixtures\/)/.test(new URL(response.url()).pathname)) failedAssets.push(`${response.status()} ${response.url()}`); });
  await page.goto("/"); await expect(cards(page)).toHaveCount(40);
  const records = await cards(page).evaluateAll(nodes => nodes.map(node => ({ id: node.getAttribute("data-product-id"), photo: node.querySelector(".product-photo-link")?.getAttribute("href"), title: node.querySelector(".product-title")?.getAttribute("href") })));
  expect(new Set(records.map(record => record.id))).toEqual(new Set(published.map(product => product.id)));
  for (const record of records) {
    const product = published.find(product => product.id === record.id)!;
    expect(record.photo).toBe(`/products/${encodeURIComponent(product.slug)}`);
    expect(record.title).toBe(record.photo);
    const card = page.locator(`[data-product-id="${product.id}"]`);
    await expect(card.locator(".product-title")).toHaveText(product.title);
    await card.locator(".product-photo-link").click();
    await expect(page.locator(".detail-copy h1")).toHaveText(product.title);
    expect(new URL(page.url()).pathname).toBe(record.photo);
    expect((await page.reload())?.status()).toBe(200);
    await expect(page.locator(".detail-copy h1")).toHaveText(product.title);
    await expect(page.getByText("Prototype. Sample listings shown.", { exact: true })).toBeVisible();
    await expect(page.locator(".detail-photo img")).toBeVisible();
    await expect.poll(() => page.locator(".detail-photo img").evaluate((node: HTMLImageElement) => node.complete && node.naturalWidth > 0)).toBe(true);
    if (!product.is_available) await expect(page.getByRole("button", { name: "Currently unavailable", exact: true })).toBeDisabled();
    await page.getByRole("link", { name: "dzirent home", exact: true }).click(); await expect(cards(page)).toHaveCount(40);
    await page.locator(`[data-product-id="${product.id}"] .product-title`).click();
    await expect(page.locator(".detail-copy h1")).toHaveText(product.title);
    await page.getByRole("link", { name: "dzirent home", exact: true }).click(); await expect(cards(page)).toHaveCount(40);
  }
  const encodedShare = `/products/%64${published[0].slug.slice(1)}`;
  expect((await page.goto(encodedShare))?.status()).toBe(200);
  await expect(page.locator(".detail-copy h1")).toHaveText(published[0].title);
  expect((await page.goto("/products/not-a-real-outfit"))?.status()).toBe(404);
  await expect(page.getByRole("heading", { name: "Outfit not found", exact: true })).toBeVisible();
  await expect(page.getByText("Prototype. Sample listings shown.", { exact: true })).toBeVisible();
  expect(failedAssets).toEqual([]);
  expect(exceptions).toEqual([]);
});
